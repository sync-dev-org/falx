class SeedTtsV3Config(BaseFalConfig):
    random_seed_field: ClassVar[str | None] = None

    app_id: Literal["bytedance/seed-tts/v3"]
    text: str = Field(
        ...,
        min_length=1,
        max_length=10000,
        description="The text to synthesize into speech.",
    )
    voice: SeedTtsV3Voice = Field(
        default="stokie_en",
        description=(
            "Voice to use for synthesis. The suffix is the voice's primary language code."
        ),
    )
    language: SeedTtsV3Language | None = Field(
        default=None,
        description=(
            "Language or dialect to read the text in. A dialect code also selects the accent, "
            "e.g. 'zh-CN-x-sichuan'. Leave unset for automatic language detection."
        ),
    )
    voice_instruction: str | None = Field(
        default=None,
        min_length=1,
        description=(
            "Optional natural-language instruction that steers the delivery (tone, emotion, "
            "pace), e.g. 'Warm and natural'. It is not spoken aloud."
        ),
    )
    speed: float = Field(
        default=1,
        ge=0.5,
        le=2,
        description="Speech speed multiplier. 1.0 is normal speed.",
    )
    volume: float = Field(
        default=1,
        ge=0.5,
        le=2,
        description="Volume multiplier. 1.0 is normal volume.",
    )
    pitch: int = Field(
        default=0,
        ge=-12,
        le=12,
        description=(
            "Pitch shift in semitones. 0 is normal pitch, -12 lowers by one octave, 12 raises "
            "by one octave."
        ),
    )
    output_format: Literal["mp3", "opus"] = Field(
        default="mp3",
        description=(
            "Output audio format. 'mp3' returns MP3 audio; 'opus' returns Opus audio in an "
            "Ogg container."
        ),
    )
    sample_rate: Literal[8000, 16000, 22050, 24000, 32000, 44100, 48000] | None = Field(
        default=None,
        description=(
            "Sample rate of the output audio in Hz. Defaults to 24000 for mp3. Opus output is "
            "always 48000 Hz."
        ),
    )
