from __future__ import annotations

from typing import Literal

from pydantic import Field

from falx.models.nano_banana_common import NanoBananaCommon, NanoBananaExtendedAspectRatio


class NanoBananaLiteCommon(NanoBananaCommon):
    """Shared parameters for nano-banana-lite generation and editing."""

    system_prompt: str = Field(
        default="",
        max_length=50000,
        description=(
            "Optional system instruction that steers the model's persona and output style "
            "across the request. Leave blank to omit; when provided, it is sent as the system "
            "instruction to Gemini (or as a system message on OpenAI-compatible providers)."
        ),
    )
    aspect_ratio: NanoBananaExtendedAspectRatio | None = Field(
        default="auto",
        description=(
            "The aspect ratio of the generated image. Supports extreme ratios: 4:1, 1:4, 8:1, "
            '1:8. Use "auto" to let the model decide based on the prompt.'
        ),
    )
    limit_generations: bool = Field(
        default=True,
        description=(
            "Experimental parameter to limit the number of generations from each round of "
            "prompting to 1. Set to `True` to to disregard any instructions in the prompt "
            "regarding the number of images to generate and ignore any intermediate images "
            "generated by the model. This may affect generation quality."
        ),
    )
    thinking_level: Literal["minimal", "high"] | None = Field(
        default=None,
        description=(
            "When set, enables model thinking with the given level ('minimal' or 'high') and "
            "includes thoughts in the generation. Omit to disable."
        ),
    )


class NanoBananaLiteConfig(NanoBananaLiteCommon):
    app_id: Literal["google/nano-banana-lite"]
