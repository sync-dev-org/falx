from __future__ import annotations

from typing import ClassVar, Literal

from pydantic import Field

from falx.models import BaseFalConfig

NanoBanana21AspectRatio = Literal[
    "auto",
    "21:9",
    "16:9",
    "3:2",
    "4:3",
    "5:4",
    "1:1",
    "4:5",
    "3:4",
    "2:3",
    "9:16",
    "4:1",
    "1:4",
    "8:1",
    "1:8",
]


class NanoBanana21Common(BaseFalConfig):
    """Shared parameters for Nano Banana 2.1 text and edit endpoints."""

    random_seed_field: ClassVar[str | None] = "seed"

    prompt: str = Field(
        ...,
        min_length=3,
        max_length=50000,
        description="The text prompt to generate an image from.",
    )
    num_images: int = Field(
        default=1,
        ge=1,
        le=4,
        description="The number of images to generate.",
    )
    seed: int | None = Field(
        default=None,
        description="The seed for the random number generator.",
    )
    aspect_ratio: NanoBanana21AspectRatio | None = Field(
        default="auto",
        description=(
            "The aspect ratio of the generated image. Supports extreme ratios: "
            '4:1, 1:4, 8:1, 1:8. Use "auto" to let the model decide based on the prompt.'
        ),
    )
    output_format: Literal["jpeg", "png", "webp"] = Field(
        default="png",
        description="The format of the generated image.",
    )
    safety_tolerance: Literal["1", "2", "3", "4", "5", "6"] = Field(
        default="4",
        description=(
            "The safety tolerance level for content moderation. "
            "1 is the most strict (blocks most content), 6 is the least strict."
        ),
    )
    sync_mode: bool = Field(
        default=False,
        description=(
            "If `True`, the media will be returned as a data URI and the output data "
            "won't be available in the request history."
        ),
    )
    system_prompt: str = Field(
        default="",
        max_length=50000,
        description=(
            "Optional system instruction that steers the model's persona and output "
            "style across the request. Leave blank to omit; when provided, it is sent "
            "as the system instruction to Gemini (or as a system message on "
            "OpenAI-compatible providers)."
        ),
    )
    resolution: Literal["1K", "2K", "4K"] = Field(
        default="1K",
        description="The resolution of the image to generate.",
    )
    limit_generations: bool = Field(
        default=True,
        description=(
            "Experimental parameter to limit the number of generations from each round "
            "of prompting to 1. Set to `True` to to disregard any instructions in the "
            "prompt regarding the number of images to generate and ignore any intermediate "
            "images generated by the model. This may affect generation quality."
        ),
    )
    enable_web_search: bool = Field(
        default=False,
        description=(
            "Enable web search for the image generation task. This will allow the model "
            "to use the latest information from the web to generate the image."
        ),
    )
    thinking_level: Literal["minimal", "medium", "high"] | None = Field(
        default="medium",
        description=(
            "How much the model reasons before generating. Higher levels can improve "
            "complex compositions and use more thinking tokens."
        ),
    )


class NanoBanana21Config(NanoBanana21Common):
    app_id: Literal["google/nano-banana-2.1"]
