from __future__ import annotations

from typing import Annotated, Any, ClassVar, Literal, Self

from pydantic import Field, model_validator

from falx.models import BaseFalConfig


class _MeshyRiggingConfig(BaseFalConfig):
    height_meters: float = Field(
        default=1.7,
        gt=0,
        description="Approximate height of the character in meters.",
    )
    skeleton_template: (
        Literal[
            "mixamo",
            "ue5_mannequin",
            "unity_humanoid",
            "maya_human_ik",
            "blender_rigify_basic_human",
            "max_biped",
            "cc5_hd_neutral_base",
            "daz_genesis9",
            "meshyrig",
        ]
        | None
    ) = Field(
        default=None,
        description=(
            "Skeleton template for the rig. Animations made from the rig use the same "
            "skeleton. Leave unset for Meshy's default skeleton (meshyrig). Some models "
            "can only be rigged on meshyrig without fingers; those requests fail with a "
            "422."
        ),
    )
    include_fingers: bool = Field(
        default=False,
        description="Rig the character's fingers. Works with any skeleton template.",
    )
    enable_safety_checker: bool = Field(
        default=True,
        description="If set to true, input data will be checked for safety before processing.",
    )


class MeshyRiggingConfig(_MeshyRiggingConfig):
    app_id: Literal["meshy/rigging"]
    model_url: str = Field(
        default=...,
        min_length=1,
        description=(
            "URL of a 3D model in GLB format to rig. Can be any publicly accessible URL — "
            "works with models generated by Hunyuan, Trellis, Meshy, or any other 3D "
            "generation tool. The model must be a humanoid character with clearly defined "
            "limbs."
        ),
    )
    enable_animation: bool = Field(
        default=False,
        description="Apply an animation preset to the rigged model.",
    )
    animation_action_id: int = Field(
        default=92,
        description=(
            "Animation preset ID from Meshy's library. Only used when enable_animation is "
            'true; in that case it must be in [0, 696] (``0`` is the "Idle" preset) and is '
            "otherwise rejected with a 422. See "
            "https://docs.meshy.ai/en/api/animation-library for available action IDs."
        ),
    )

    @model_validator(mode="after")
    def validate_animation_action(self) -> Self:
        if self.enable_animation and not 0 <= self.animation_action_id <= 696:
            raise ValueError("animation_action_id must be between 0 and 696")
        return self


class MeshyRiggingMultiAnimationConfig(_MeshyRiggingConfig):
    schema_example_parameters: ClassVar[dict[str, Any]] = {"animation_action_ids": [36, 92]}

    app_id: Literal["meshy/rigging/multi-animation"]
    model_url: str = Field(
        default=...,
        min_length=1,
        description=(
            "URL of a 3D model in GLB format to rig and animate. Can be any publicly "
            "accessible URL — works with models generated by Hunyuan, Trellis, Meshy, or "
            "any other 3D generation tool. The model must be a humanoid character with "
            "clearly defined limbs."
        ),
    )
    animation_action_ids: list[Annotated[int, Field(ge=0, le=696)]] = Field(
        default=...,
        min_length=1,
        description=(
            "Animation preset IDs from Meshy's library. One animation clip is generated "
            "per ID against the same rig and returned in the 'animations' output array, in "
            "request order. Must contain at least one ID. Each ID must be in [0, 696], at "
            "most 10 distinct clips may be requested, and duplicate IDs are de-duplicated. "
            "See https://docs.meshy.ai/en/api/animation-library for available IDs."
        ),
    )

    @model_validator(mode="after")
    def validate_distinct_clip_count(self) -> Self:
        if len(set(self.animation_action_ids)) > 10:
            raise ValueError("animation_action_ids may request at most 10 distinct clips")
        return self
